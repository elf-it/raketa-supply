from __future__ import annotations

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    app_name: str = "Ракета · Веб-система снабжения"
    #: SQLite по умолчанию, чтобы проект поднимался без Docker.
    #: В проде — postgresql+psycopg://user:pass@host:5432/raketa
    database_url: str = "sqlite:///./raketa.db"
    cors_origins: str = "http://localhost:5173,http://127.0.0.1:5173"
    #: Источник данных WB: ``fixtures`` (локальные файлы) или ``http`` (реальный API).
    wb_client: str = "fixtures"
    wb_api_base: str = "https://statistics-api.wildberries.ru"
    #: Ключи кабинетов задаются только через окружение, в базе не хранятся:
    #: WB_TOKENS="store01=eyJ...,store02=eyJ..."
    wb_tokens: str = ""
    #: Где лежат выгрузки для ``WB_CLIENT=fixtures``. Пусто — рядом с кодом.
    #: Тот же смысл, что у ключа `--fixtures-dir` у сида: сгенерированные
    #: выгрузки не всегда уместно держать в репозитории.
    wb_fixtures_dir: str = ""

    #: Лимиты и повторы запросов в WB (задача E-5). Значения по умолчанию —
    #: из документации WB: у метода «Продажи» лимит 1 запрос в минуту
    #: на профиль продавца, превышение даёт 429, а ответ 4XX считается
    #: за десять запросов. Подробности — app/integrations/wb/limits.py.
    #: Фикстурного клиента это не касается: паузы нужны только живому API.
    wb_max_attempts: int = 4
    wb_retry_backoff_seconds: float = 2.0
    #: Предел одной паузы: ответ «подождите час» не должен держать прогон час
    #: и занимать блокировку загрузки.
    wb_max_wait_seconds: float = 120.0
    wb_min_interval_seconds: float = 60.0
    #: Предел страниц на метод. По 80 000 строк на страницу — это 1,6 млн строк;
    #: при минуте на запрос двадцать страниц укладываются в 20 минут, то есть
    #: внутрь получаса, после которых прогон считается брошенным (`--lock-minutes`).
    wb_max_pages: int = 20

    #: Откуда брать остатки (задача E-8): ``report`` — отчёт
    #: `/api/v1/warehouse_remains` в три шага, как описано в документации
    #: сейчас; ``legacy`` — прежний путь `/api/v1/supplier/stocks`, которого
    #: в документации больше нет. По умолчанию отчёт. Запасной путь оставлен
    #: потому, что ни один из двух не проверен на боевом ключе, а отчёту нужен
    #: токен категории «Аналитика» — его у кабинета может не оказаться.
    wb_stocks_source: str = "report"
    #: Пауза между проверками готовности отчёта: у этого шага лимит 1 запрос
    #: в 5 секунд, а не в минуту.
    wb_status_interval_seconds: float = 5.0
    #: Сколько всего ждать готовности отчёта об остатках.
    wb_report_wait_seconds: float = 300.0
    debug: bool = True

    #: Ключ подписи сессионных токенов. В проде задаётся только через окружение.
    secret_key: str = "dev-only-insecure-key-change-me"
    session_ttl_hours: int = 12
    #: Кука только по HTTPS. В разработке выключено, иначе вход не работает по http.
    cookie_secure: bool = False

    #: Ограничение перебора паролей: сколько неудачных попыток подряд допускается
    #: с одного адреса для одной почты и сколько — с адреса на все учётные записи.
    #: За обратным прокси без проброса адреса второй порог придётся поднять:
    #: там весь офис выглядит одним клиентом. Подробности — app/ratelimit.py.
    login_max_attempts: int = 10
    login_max_attempts_per_address: int = 60
    login_window_minutes: int = 15

    #: Сколько доверенных прокси стоит перед приложением (задача G-12).
    #: 0 — приложение видит клиента напрямую, и ``X-Forwarded-For`` не читается:
    #: без прокси этот заголовок подставляет сам клиент, и счётчик по адресу
    #: обходился бы одной строкой в запросе. За одним nginx — 1.
    trusted_proxy_hops: int = 0

    #: Кэш недельных рядов: сколько записей «пара × ось недель» держать в памяти
    #: процесса. Запись — около 0,2 КБ на неделю оси, то есть 8 КБ на замеренных
    #: осях матрицы и закупки; предел по умолчанию — это потолок примерно
    #: в 80 МБ на воркер, а занято будет ровно по каталогу. Каждая пара занимает
    #: по записи на экран: 5000 пар — это 10 000 записей.
    #: Предел меньше каталога бесполезен: запрос обходит все пары подряд
    #: и вытесняет то, что сам же положил. 0 выключает кэш — расчёт идёт
    #: на каждый запрос, как до задачи G-13.
    #: Подробности — app/services/calc_cache.py и docs/08-performance.md.
    calc_cache_entries: int = 10_000

    #: Общий кэш расчёта на все процессы (задача G-14): адрес Redis вида
    #: ``redis://redis:6379/0``. Пусто — кэш только в памяти процесса, как было.
    #: Включать имеет смысл там, где воркеров несколько или перезапуски часты:
    #: номера версий входят в ключ, поэтому устаревшая запись просто
    #: не находится, а срок жизни убирает ненужные ключи.
    calc_cache_url: str = ""
    calc_cache_ttl_seconds: int = 3600

    #: Логи (задача G-4). ``text`` — человеку в терминал, ``json`` — сборщику
    #: логов: по строке-объекту на событие. Уровень ``DEBUG`` добавляет к строке
    #: запроса ещё и SQL, если его включит сам SQLAlchemy.
    log_level: str = "INFO"
    log_format: str = "text"

    #: Через сколько часов без удачной загрузки кабинет считается отставшим.
    #: Сутки с запасом: суточная загрузка, запущенная вчера утром и не
    #: запущенная сегодня, должна успеть попасть в «устарело» до того,
    #: как по этим числам соберут заказ.
    sync_stale_hours: int = 36

    #: Доставка алертов (задача G-16). Пусто — система о сбоях не сообщает,
    #: и о них узнаёт только внешний мониторинг по `/health/ready` и человек
    #: по плашке в интерфейсе. Настроенным считается тот канал, у которого
    #: заполнено всё нужное: полунастроенный канал приложение не пускает
    #: к старту — молча не отправленный алерт хуже отсутствующего.
    smtp_host: str = ""
    #: 0 — порт по режиму: 465 для ssl, 587 для starttls, 25 без шифрования.
    smtp_port: int = 0
    smtp_user: str = ""
    smtp_password: str = ""
    #: ``starttls`` (обычный путь), ``ssl`` (SMTPS) или ``none``.
    smtp_security: str = "starttls"
    alert_email_from: str = ""
    #: Кому слать, через запятую.
    alert_email_to: str = ""
    #: Входящий вебхук мессенджера: Slack, Mattermost, Telegram.
    #: Сам адрес — секрет (в нём ключ входящего вебхука), поэтому в логах
    #: и в выводе команд он маскируется.
    alert_webhook_url: str = ""
    #: Только для Telegram: номер чата уходит в теле запроса рядом с текстом.
    alert_webhook_chat_id: str = ""
    #: Через сколько часов напоминать о неисправленном сбое. 0 — не повторять:
    #: сообщить один раз и молчать до изменения состояния.
    alert_repeat_hours: int = 24
    #: Приставка к теме письма и первой строке сообщения — чтобы правило
    #: в почте или фильтр в мессенджере опознавали алерты этой системы.
    alert_subject_prefix: str = "[Ракета]"

    def validate_runtime(self) -> None:
        """Проверки, после которых приложению можно давать работать.

        Токен, подписанный общеизвестным ключом, подделывается кем угодно, поэтому
        с ключом по умолчанию вне отладки стартовать нельзя.
        """
        if not self.debug and self.secret_key == Settings.model_fields["secret_key"].default:
            raise RuntimeError(
                "SECRET_KEY не задан. Сгенерируйте ключ "
                '(`python -c "import secrets; print(secrets.token_urlsafe(48))"`) '
                "и передайте его через окружение."
            )
        if not self.debug and not self.cookie_secure:
            raise RuntimeError(
                "COOKIE_SECURE=false вне отладки: сессионная кука уйдёт по открытому HTTP."
            )
        # Полунастроенная доставка алертов — отказ старта, а не молчание:
        # «алерты настроены» и «алерты не уходят» вместе дают самый дорогой
        # вид сбоя — тот, о котором никто не узнает. Ввоз здесь, а не наверху
        # модуля: каналы доставки сами читают настройки.
        from .services.notify import check_config

        check_config(self)

    @property
    def cors_origin_list(self) -> list[str]:
        return [o.strip() for o in self.cors_origins.split(",") if o.strip()]

    @property
    def alert_email_list(self) -> list[str]:
        return [a.strip() for a in self.alert_email_to.split(",") if a.strip()]

    @property
    def wb_token_map(self) -> dict[str, str]:
        out: dict[str, str] = {}
        for item in self.wb_tokens.split(","):
            if "=" in item:
                code, token = item.split("=", 1)
                out[code.strip()] = token.strip()
        return out


@lru_cache
def get_settings() -> Settings:
    return Settings()
