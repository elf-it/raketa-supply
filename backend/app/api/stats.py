"""Счётчики работы системы (задача G-14).

Кэш расчёта — главный источник вопросов «почему то быстро, то медленно».
Числа отвечают на них сами: сколько записей лежит, сколько раз они пригодились
и сколько раз пришлось считать заново. По ним же принимается решение, нужен ли
общий кэш на несколько процессов, — угадывать его раньше реальных объёмов
(вопрос Q-9) значило бы ставить Redis вслепую.

Ручка закрыта ролью: числа говорят и о размере каталога.
"""

from __future__ import annotations

from fastapi import APIRouter

from ..services.calc_cache import get_series_cache

router = APIRouter(prefix="/stats", tags=["Служебное"])


@router.get("/calc-cache", summary="Счётчики кэша расчёта")
def calc_cache_stats() -> dict:
    """Записи, попадания, промахи, вытеснения и состояние общего хранилища.

    Счётчики процесса, а не всей установки: за несколькими воркерами каждый
    ответит про себя — это тот самый случай, ради которого и смотрят, стоит ли
    включать общий кэш.
    """
    return get_series_cache().stats()
