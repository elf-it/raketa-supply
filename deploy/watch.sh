#!/usr/bin/env bash
# Сам замечает проверенные правки и перезапускает (задачи A-10, A-11).
# Таймер systemd раз в две минуты; на сервере он же команда `raketa-watch`.
#
# Решения и почему так:
#
# * **Сервер спрашивает GitHub, а не GitHub стучится на сервер.** Обратный
#   способ (рабочий процесс Actions ходит по ssh) быстрее на эти две минуты,
#   но требует приватного ключа в секретах репозитория — а секреты читает
#   всякий, кто может менять рабочие процессы. Вариант с Actions оставлен
#   включаемым: .github/workflows/deploy.yml и переменная DEPLOY_ENABLED.
#
# * **Проверенное отмечает сам CI — указателем в репозитории.** Ветка
#   `ci-green` переставляется на коммит, прошедший проверки (см. ci.yml),
#   и сторожу остаётся сравнить её с тем, что развёрнуто. Прежде он
#   спрашивал состояние проверок у публичного API GitHub; на приватном
#   репозитории такой запрос требует токена — то есть ещё одного секрета
#   на машине и ещё одного срока его действия. Указатель читается тем же
#   ключом, которым сервер и так забирает код, и предела запросов у него нет.
#
# * **Выкладывается только проверенное.** Выложить красный main — значит
#   уронить сайт правкой, о которой уже известно, что она сломана. Пока
#   проверки идут, `ci-green` указывает на прежний коммит, и тик ничего
#   не делает.
#
# * **В журнал пишется только смена состояния.** Иначе один и тот же ответ
#   шёл бы строкой каждые две минуты, и журнал пришлось бы читать
#   по диагонали.
set -euo pipefail

# Работа с копии: выкладка перезаписывает файл этого скрипта (`git reset`),
# а bash читает его по мере выполнения. Подробное объяснение — в deploy.sh.
case "$0" in
    /tmp/raketa-run.*) trap 'rm -f "$0"' EXIT ;;
    *)
        self=$(mktemp /tmp/raketa-run.XXXXXX)
        cat "$0" > "$self"
        exec bash "$self" "$@"
        ;;
esac

APP_DIR=${APP_DIR:-/opt/raketa}
#: Указатель на проверенное. Его ставит CI; руками эту ветку не двигают.
GREEN_REF=${GREEN_REF:-ci-green}
#: Ветка разработки — нужна только чтобы отличить «правок нет» от «правки
#: есть, но CI до отметки не дошёл». Это разные вещи, и молчать об одной
#: из них словами другой нельзя.
MAIN_REF=${MAIN_REF:-main}
STATE=${STATE:-$APP_DIR/.watch-state}
DEPLOY=${DEPLOY:-/usr/local/bin/raketa-deploy}

cd "$APP_DIR"

note() {
    # Повтор того же состояния в журнал не идёт.
    local line="$1"
    if [ "$(cat "$STATE" 2>/dev/null || true)" != "$line" ]; then
        printf '%s\n' "$line"
        printf '%s' "$line" > "$STATE"
    fi
}

# Один запрос на оба указателя: лишний вызов ничего не добавляет.
refs=$(git ls-remote origin "refs/heads/$GREEN_REF" "refs/heads/$MAIN_REF" 2>/dev/null || true)
green=$(printf '%s\n' "$refs" | awk -v r="refs/heads/$GREEN_REF" '$2 == r {print $1}')
tip=$(printf '%s\n' "$refs" | awk -v r="refs/heads/$MAIN_REF" '$2 == r {print $1}')

if [ -z "$green" ] && [ -n "$tip" ]; then
    # Репозиторий читается, а отметки нет вовсе: CI ни разу не дошёл до неё.
    note "отметки $GREEN_REF нет, а main на ${tip:0:7}: CI не ставил отметку ни разу"
    exit 0
fi
if [ -z "$green" ]; then
    # Либо GitHub недоступен, либо ключ доступа перестал работать, либо CI
    # ни разу не доходил до отметки. Во всех случаях выкладывать нечего,
    # и молчать об этом нельзя: иначе сервер «работает», а правки не едут.
    note "нет отметки проверенного ($GREEN_REF): GitHub недоступен или нет доступа"
    exit 0
fi

if [ "$green" = "$(git rev-parse HEAD)" ]; then
    if [ -n "$tip" ] && [ "$tip" != "$green" ]; then
        # Выложено всё проверенное — но в main лежит непроверенное. Сказать
        # здесь «правок нет» значило бы назвать застрявший CI исправной
        # работой: именно так простой CI из-за оплаты минут прожил незамеченным.
        note "выложено проверенное ${green:0:7}, но main на ${tip:0:7}: CI до отметки не дошёл"
    else
        note "правок нет: $(git rev-parse --short HEAD)"
    fi
    exit 0
fi

note "${green:0:7}: проверено — развёртываю"
# Своя копия удаляется до exec: после него этот процесс перестаёт
# существовать, и убрать за собой было бы некому.
case "$0" in /tmp/raketa-run.*) rm -f "$0" ;; esac
exec "$DEPLOY"
